local mapping = require('toggle.mapping')

describe('mapping', function()
    it('__reset clears mapping', function()
        mapping.__register({ 'foo', 'bar' })
        mapping.__register({ 'foo', 'bar' }, 'testftp')
        mapping.__reset()
        assert(mapping.__has_mapping('foo') == false)
        assert(mapping.__has_mapping('bar') == false)
        assert(mapping.__has_mapping('foo', 'testftp') == false)
        assert(mapping.__has_mapping('bar', 'testftp') == false)
    end)

    it('__get_mapping - existing mapping', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' })
        assert(mapping.__get_mapping('foo') == 'bar')
        assert(mapping.__get_mapping('bar') == 'foo')
    end)

    it('__get_mapping - existing mapping by filetype', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' })
        mapping.__register({ 'foo1', 'bar1' }, 'ftp1')
        assert(mapping.__get_mapping('foo') == 'bar')
        assert(mapping.__get_mapping('bar') == 'foo')
        assert(mapping.__get_mapping('foo1', 'ftp1') == 'bar1')
        assert(mapping.__get_mapping('bar1', 'ftp1') == 'foo1')
    end)

    it('__get_mapping - by filetype defaults to general mapping on non-existing mapping', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' })
        mapping.__register({ 'meow', 'woof' }, 'ftp1')
        assert(mapping.__get_mapping('foo') == 'bar')
        assert(mapping.__get_mapping('bar') == 'foo')
        assert(mapping.__get_mapping('foo', 'ftp1') == 'bar')
    end)

    it('__get_mapping - chain of mappings', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'zoo' })
        assert(mapping.__get_mapping('foo') == 'bar')
        assert(mapping.__get_mapping('bar') == 'zoo')
        assert(mapping.__get_mapping('zoo') == 'foo')
    end)

    it('__get_mapping - chain of mappings by filetype', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'zoo' }, 'ftp1')
        assert(mapping.__get_mapping('foo', 'ftp1') == 'bar')
        assert(mapping.__get_mapping('bar', 'ftp1') == 'zoo')
        assert(mapping.__get_mapping('zoo', 'ftp1') == 'foo')
    end)

    it('__get_mapping - non-existing mapping', function()
        mapping.__reset()
        assert(mapping.__get_mapping('non-existing') == nil)
    end)

    it('__get_mapping - non-existing mapping on general does not lead to by filetype', function()
        mapping.__reset()
        mapping.__register({ 'non-existing', 'zoo' }, 'ftp1')
        assert(mapping.__get_mapping('non-existing') == nil)
    end)

    it('__register - empty', function()
        mapping.__register({})
    end)

    it('__register - null', function()
        mapping.__register(nil)
    end)

    it('__register - happy path', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'zoo' })
        assert(mapping.__has_mapping('foo'))
        assert(mapping.__has_mapping('bar'))
        assert(mapping.__has_mapping('zoo'))
    end)

    it('__register - by filetype', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'zoo' }, 'myftp')
        assert(mapping.__has_mapping('foo', 'myftp'))
        assert(mapping.__has_mapping('bar', 'myftp'))
        assert(mapping.__has_mapping('zoo', 'myftp'))
        assert(not mapping.__has_mapping('foo', 'nonexisting'))
        assert(not mapping.__has_mapping('bar', 'nonexisting'))
        assert(not mapping.__has_mapping('zoo', 'nonexisting'))
        assert(not mapping.__has_mapping('foo'))
        assert(not mapping.__has_mapping('bar'))
        assert(not mapping.__has_mapping('zoo'))
    end)

    it('__has_mapping - existing map', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' })
        assert(mapping.__has_mapping('foo'))
        assert(mapping.__has_mapping('bar'))
    end)

    it('__has_mapping - nil', function()
        assert(not mapping.__has_mapping(nil))
    end)

    it('__has_mapping - existing map by filetype', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' }, 'test')
        assert(mapping.__has_mapping('foo', 'test'))
        assert(mapping.__has_mapping('bar', 'test'))
        assert(not mapping.__has_mapping('foo'))
        assert(not mapping.__has_mapping('bar'))
    end)

    it('__get_previous_mapping - existing mapping', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' })
        assert(mapping.__get_previous_mapping('foo') == 'bar')
        assert(mapping.__get_previous_mapping('bar') == 'foo')
    end)

    it('__get_previous_mapping - existing mapping by filetype', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar' }, 'test')
        assert(mapping.__get_previous_mapping('foo', 'test') == 'bar')
        assert(mapping.__get_previous_mapping('bar', 'test') == 'foo')
    end)

    it('__get_previous_mapping - chain of mappings', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'zoo' })
        assert(mapping.__get_previous_mapping('foo') == 'zoo')
        assert(mapping.__get_previous_mapping('bar') == 'foo')
        assert(mapping.__get_previous_mapping('zoo') == 'bar')
    end)

    it('__get_previous_mapping - chain of mappings by filetype', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'zoo' }, 'test')
        assert(mapping.__get_previous_mapping('foo', 'test') == 'zoo')
        assert(mapping.__get_previous_mapping('bar', 'test') == 'foo')
        assert(mapping.__get_previous_mapping('zoo', 'test') == 'bar')
    end)

    it('__get_previous_mapping - chain of mappings by filetype does not mix with default mappings', function()
        mapping.__reset()
        mapping.__register({ 'foo', 'bar', 'whoa' })
        mapping.__register({ 'foo', 'bar', 'zoo' }, 'test')
        assert(mapping.__get_previous_mapping('foo', 'test') == 'zoo')
        assert(mapping.__get_previous_mapping('bar', 'test') == 'foo')
        assert(mapping.__get_previous_mapping('zoo', 'test') == 'bar')
    end)

    it('__get_previous_mapping - non-existing mapping by filetype', function()
        mapping.__reset()
        assert(mapping.__get_previous_mapping('non-existing', 'test') == nil)
    end)

    it('__get_previous_mapping - non-existing mapping', function()
        mapping.__reset()
        assert(mapping.__get_previous_mapping('non-existing') == nil)
    end)
end)
